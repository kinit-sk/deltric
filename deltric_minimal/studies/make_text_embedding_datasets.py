"""Generate real-embedding text-clustering datasets via DeepInfra.

Unlike the synthetic geometric datasets in ``data/`` (blobs, moons, ...),
this script builds a short-text clustering benchmark from scratch: template
-generated sentences across several realistic customer-support-ticket
categories, plus a block of off-topic noise sentences that belong to no
category, embedded through several different DeepInfra embedding models so
the same cluster structure can be compared across embedding spaces.

Categories (the "clusters", label 0..7):
  0 billing_and_payment      1 login_account_access
  2 shipping_delivery        3 product_defect_bug_report
  4 feature_request          5 refund_cancellation
  6 technical_setup          7 subscription_plan_change
Noise (label -1): off-topic sentences (trivia, weather, small talk, ...)
unrelated to any support category.

Sentences are generated by combinatorial slot-filling templates (not
downloaded from any dataset), so lexical content is synthetic but each
category is topically coherent the way real ticket text would be.

Output: one ``.npz`` per embedding model, following this repo's
``<family>__<params>.npz`` naming convention:

    text_support_tickets__<model_slug>.npz
      X     (n, dim) float32   embedding vectors
      y     (n,) int64         0..7 category label, -1 for noise
      text  (n,) object/str    the original sentence
    plus a shared ``text_support_tickets.json`` sidecar with generation
    metadata (identical text/labels are used for every model).

Usage:
    export DEEPINFRA_TOKEN=...
    python studies/make_text_embedding_datasets.py
    python studies/make_text_embedding_datasets.py --n-per-cluster 100 --noise-rate 0.15
    python studies/make_text_embedding_datasets.py --models BAAI/bge-m3 --dry-run
"""

