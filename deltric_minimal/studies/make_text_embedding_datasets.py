def build_texts(n_per_cluster: int, noise_rate: float, seed: int):
    rng = np.random.default_rng(seed)
    texts: list[str] = []
    labels: list[int] = []
    for label, cat in enumerate(CATEGORY_NAMES):
        templates = TEMPLATES[cat]
        seen = set()
        made = 0
        attempts = 0
        while made < n_per_cluster and attempts < n_per_cluster * 40:
            attempts += 1
            t = rng.choice(templates)
            s = t.format(
                opener=rng.choice(POLITE_OPENERS),
                product=rng.choice(PRODUCTS),
                cust=rng.choice(CUSTOMERS),
            ).replace("  ", " ").strip()
            # fix "I was" vs "We was" agreement roughly (cheap, not exhaustive)
            if s in seen:
                continue
            seen.add(s)
            texts.append(s)
            labels.append(label)
            made += 1
        if made < n_per_cluster:
            print(f"  ! {cat}: only produced {made}/{n_per_cluster} unique sentences")

    n_signal = len(texts)
    n_noise = int(round(noise_rate * n_signal / (1.0 - noise_rate)))
    noise_seen = set()
    noise_texts = []
    attempts = 0
    while len(noise_texts) < n_noise and attempts < n_noise * 40:
        attempts += 1
        s = rng.choice(NOISE_TEMPLATES)
        if s in noise_seen:
            continue
        noise_seen.add(s)
        noise_texts.append(s)
    if len(noise_texts) < n_noise:
        # allow repeats once the pool of 25 fixed sentences is exhausted
        while len(noise_texts) < n_noise:
            noise_texts.append(rng.choice(NOISE_TEMPLATES))

    texts += noise_texts
    labels += [-1] * len(noise_texts)

    order = rng.permutation(len(texts))
    texts = [texts[i] for i in order]
    labels = np.asarray(labels, dtype=np.int64)[order]
    return texts, labels


def embed_batch(texts: list[str], model: str, token: str, batch_size: int = 64,
                 retries: int = 4) -> np.ndarray:
    vecs: list[list[float]] = []
    for start in range(0, len(texts), batch_size):
        chunk = texts[start:start + batch_size]
        body = json.dumps({"input": chunk, "model": model, "encoding_format": "float"}).encode()
        req = urllib.request.Request(
            DEEPINFRA_URL, data=body,
            headers={"Content-Type": "application/json", "Authorization": f"Bearer {token}"},
            method="POST",
        )
        for attempt in range(retries):
            try:
                with urllib.request.urlopen(req, timeout=120) as resp:
                    payload = json.loads(resp.read())
                break
            except urllib.error.HTTPError as e:
                err_body = e.read().decode(errors="replace")
                if e.code in (429, 500, 502, 503) and attempt < retries - 1:
                    wait = 2 ** attempt
                    print(f"    HTTP {e.code}, retrying in {wait}s: {err_body[:200]}")
                    time.sleep(wait)
                    continue
                raise RuntimeError(f"DeepInfra HTTP {e.code} for {model}: {err_body[:500]}") from e
        data = sorted(payload["data"], key=lambda d: d["index"])
        vecs.extend(d["embedding"] for d in data)
        print(f"    {model}: {min(start + batch_size, len(texts))}/{len(texts)}")
    return np.asarray(vecs, dtype=np.float32)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                      formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=_DEFAULT_DATA_DIR, type=Path)
    parser.add_argument("--n-per-cluster", type=int, default=85)
    parser.add_argument("--noise-rate", type=float, default=0.15)
    parser.add_argument("--models", nargs="*", default=list(MODELS.keys()), choices=list(MODELS.keys()))
    parser.add_argument("--batch-size", type=int, default=64)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--token", default=None, help="DeepInfra API token; default env DEEPINFRA_TOKEN")
    parser.add_argument("--dry-run", action="store_true", help="build text/labels only, skip API calls")
    args = parser.parse_args()

    import os
    token = args.token or os.environ.get("DEEPINFRA_TOKEN")
    if not args.dry_run and not token:
        raise SystemExit("set DEEPINFRA_TOKEN env var or pass --token")

    texts, y = build_texts(args.n_per_cluster, args.noise_rate, args.seed)
    n = len(texts)
    n_noise = int((y == -1).sum())
    print(f"{n} texts: {n - n_noise} signal across {len(CATEGORY_NAMES)} categories, "
          f"{n_noise} noise ({n_noise / n:.1%})")

    stem = "text_support_tickets"
    args.out.mkdir(parents=True, exist_ok=True)
    sidecar_path = args.out / f"{stem}.json"
    existing_models = {}
    if sidecar_path.exists():
        existing_models = json.loads(sidecar_path.read_text()).get("models", {})
    meta = {
        "categories": CATEGORY_NAMES, "n_per_cluster": args.n_per_cluster,
        "n_signal": n - n_noise, "n_noise": n_noise,
        "noise_rate_actual": round(n_noise / n, 4), "seed": args.seed,
        "models": existing_models,
        "note": "sentences are template-generated, not downloaded from any dataset",
    }

    if args.dry_run:
        print("[dry run] skipping embedding calls")
        for t, lab in list(zip(texts, y))[:5]:
            print(f"  y={lab:>3}  {t}")
        return

    for model in args.models:
        slug = MODELS[model]
        print(f"embedding with {model} ...")
        X = embed_batch(texts, model, token, batch_size=args.batch_size)
        out_path = args.out / f"{stem}__{slug}.npz"
        np.savez_compressed(
            out_path, X=X, y=y,
            text=np.asarray(texts, dtype=object),
        )
        meta["models"][model] = {"dim": int(X.shape[1]), "file": out_path.name}
        print(f"  wrote {out_path} X={X.shape}")

    (args.out / f"{stem}.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(f"done. sidecar metadata: {args.out / f'{stem}.json'}")


if __name__ == "__main__":
    main()
