def observe(labels, edges, lengths, core, p=.5, q=.5, reach=15.):
    """Trace the real function rather than copying its queue implementation."""
    claims = []
    observed = 0
    def trace(frame, event, arg):
        nonlocal observed
        if event == "line":
            z = frame.f_locals
            count = z.get("diagnostics", {}).get("n_claims", 0)
            if count > observed:
                observed = count
                claims.append(dict(claim=count, node=int(z["node"]),
                    cluster=int(z["cluster"]), cost=float(z["distance"]),
                    edge=int(z["edge_index"])))
        return trace
    previous = sys.gettrace()
    try:
        sys.settrace(lambda f, e, a: trace if f.f_code is FN.__code__ else None)
        pred, diag = FN(labels, edges, lengths, len(labels), p, reach,
                       core_distance=core, density_power=q, density_clip=False)
    finally:
        sys.settrace(previous)
    assert len(claims) == diag["n_claims"]
    assert all(a["cost"] <= b["cost"] for a, b in zip(claims, claims[1:]))
    assert all(labels[c["node"]] == -1 and pred[c["node"]] == c["cluster"] for c in claims)
    return pred, claims


def controlled(right_core, reach, p=.5, q=.5):
    edges = [(0,1), (0,2)] + [(i,i+1) for i in range(2,9)]
    edges += [(1,10)] + [(i,i+1) for i in range(10,17)]
    labels = np.r_[0, 0, np.full(16,-1)]
    core = np.ones(18); core[10:] = right_core
    pred, claims = observe(labels, np.array(edges), np.ones(len(edges)), core, p, q, reach)
    for c in claims:
        c["side"] = "left" if c["node"] < 10 else "right"
    left = [c for c in claims if c["side"] == "left"]
    right = [c for c in claims if c["side"] == "right"]
    left_finish = left[-1]["claim"] if len(left)==8 else None
    return dict(p=p, q=q, reach=reach, right_core=right_core,
                hop_cost_ratio=right_core**(q*(1+p)),
                left_claimed=len(left), right_claimed=len(right),
                left_finished_at_claim=left_finish,
                right_claimed_when_left_finished=sum(c["claim"]<=left_finish for c in right)
                if left_finish else None, trace=claims)


def equal_cost_layer():
    """All 16 claims have equal cost; node IDs decide playback ordering."""
    edges=np.array([(0,1)]+[(0,i) for i in range(2,10)]+[(1,i) for i in range(10,18)])
    labels=np.r_[0,0,np.full(16,-1)]
    _,claims=observe(labels,edges,np.ones(len(edges)),np.ones(18),reach=15.)
    assert all(c["cost"]==1. for c in claims)
    assert [c["node"] for c in claims]==list(range(2,18))
    return dict(cost_of_every_claim=1.,left_claims_in_first_half=8,
                right_claims_in_first_half=0,left_final=8,right_final=8,
                interpretation="Equal-cost points are serialized by node ID; no cost-front difference.")


def dataset(name, folder, tag):
    a = np.load(folder / (name+".npz"))
    meta = json.loads((folder / (name+".json")).read_text())
    d = np.load(ROOT / "data" / (name+".npz"))
    X, y = StandardScaler().fit_transform(d["X"]), d["y"]
    edges = a["edge_keys"]
    cc, bearing = audit.stage._final_graph_components(edges, a["final_retained_mask"], len(X))
    base = audit.stage._final_component_prediction(edges, a["final_retained_mask"], cc, bearing, 10)
    lengths = np.linalg.norm(X[edges[:,0]]-X[edges[:,1]], axis=1)
    core = audit._knn_core_distance(X,15)
    reach = meta["outlier_growth_metrics"]["reach"]
    pred, claims = observe(base, edges, lengths, core, reach=reach)
    assert np.array_equal(pred,a["final_prediction"])
    nodes = np.array([c["node"] for c in claims],dtype=int)
    costs = np.array([c["cost"] for c in claims])
    order=np.random.default_rng(20261008).permutation(len(X))
    old_to_new=np.argsort(order)
    perm_pred,perm_claims=observe(base[order],old_to_new[edges],lengths,core[order],reach=reach)
    permutation_final_changes=int((pred!=perm_pred[old_to_new]).sum())
    perm_nodes=order[np.array([c["node"] for c in perm_claims],dtype=int)]
    order_changes=int((nodes!=perm_nodes).sum()) if len(nodes)==len(perm_nodes) else None
    classes = []
    for c in np.unique(y):
        eligible = int(((base<0)&(y==c)).sum())
        selected = y[nodes]==c
        counts = np.r_[0,np.cumsum(selected)]
        total = int(selected.sum())
        classes.append(dict(truth_class=int(c), initially_unassigned=eligible,
            reclaimed=total, reclaimed_fraction=total/eligible if eligible else None,
            median_claim_cost=float(np.median(costs[selected])) if total else None,
            by_first_quarter=int(selected[:len(claims)//4].sum()),
            fraction_of_own_final_claims_by_first_quarter=float(selected[:len(claims)//4].sum()/total)
                if total else None))
    np.savez_compressed(OUT/(tag+"__"+name+".npz"), base=base, final=pred, y=y,
                        nodes=nodes, costs=costs, projected=a["X_proj"])
    return dict(dataset=name,run=tag,reach=reach,n_claims=len(claims),classes=classes,
                final_replay_verified=True,permutation_changed_assignments=permutation_final_changes,
                permutation_changed_claim_order_positions=order_changes,trace=claims)


def figures(controls, datasets):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, axes = plt.subplots(1,3,figsize=(14,4.4))
    for ax,control,title in zip(axes,controls[:3],
            ["Equal sides", "Unequal costs; both finish", "Same costs; budget stops right side"]):
        trace=control["trace"]
        for side,color in [("left","#2563eb"),("right","#ea580c")]:
            counts=np.r_[0,np.cumsum([c["side"]==side for c in trace])]
            ax.step(np.arange(len(counts)),counts,where="post",label=side.title(),color=color)
        ax.set(title=title,xlabel="Global claim number (animation order)",ylabel="Points reclaimed on this side",
               ylim=(0,8.5))
        ax.legend();ax.grid(alpha=.2)
    fig.suptitle("Anomaly reassignment: appearing earlier and reaching farther are different effects")
    fig.text(.5,.015,"Actual function traced; p=q=0.5. Middle/right: right neighbor-spacing input ×4. Reach budgets: 30, 30, 15.",ha="center",fontsize=9)
    fig.tight_layout(rect=(0,.05,1,.93));fig.savefig(OUT/"controlled_claim_order.png",dpi=160);plt.close(fig)
    fig,axes=plt.subplots(1,2,figsize=(12,4.6))
    for ax,result,title in zip(axes,datasets[:2],["Current unequal-density blobs","Current two moons"]):
        a=np.load(OUT/(result["run"]+"__"+result["dataset"]+".npz"))
        nodes,y=a["nodes"],a["y"]
        for c in np.unique(y[nodes]):
            hit=y[nodes]==c
            curve=np.r_[0,np.cumsum(hit)]/hit.sum()*100
            ax.step(np.arange(len(curve)),curve,where="post",label=f"Reference class {c}")
        ax.set(title=title,xlabel="Global claim number",ylabel="% of this class's eventual reassignments",ylim=(0,105))
        ax.grid(alpha=.2);ax.legend(fontsize=8)
    fig.suptitle("Different regions are reclaimed at different points in the queue")
    fig.text(.5,.01,"Curves normalize by eventual reassignments, not initial cluster size. They show timing/order, not accuracy or spatial direction.",ha="center",fontsize=9)
    fig.tight_layout(rect=(0,.04,1,.93));fig.savefig(OUT/"dataset_claim_order.png",dpi=160);plt.close(fig)


def main():
    OUT.mkdir(parents=True,exist_ok=True)
    controls=[controlled(1.,30.),controlled(4.,30.),controlled(4.,15.),controlled(2.,25.,3.,4.)]
    assert controls[0]["left_claimed"]==controls[0]["right_claimed"]==8
    assert controls[1]["right_claimed"]==8 and controls[1]["right_claimed_when_left_finished"]==2
    assert controls[2]["left_claimed"]==8 and controls[2]["right_claimed"]==5
    assert controls[3]["hop_cost_ratio"]==65536 and controls[3]["right_claimed"]==0
    equal_layer=equal_cost_layer()
    datasets=[dataset("varied_2d_5c",audit.OUT/"current_varied","current"),
              dataset("11_v2_moons_2d_2500",audit.OUT/"current_moons","current"),
              dataset("04_v3_vardensity_blobs_20d_4500_k6",audit.SAVED,"historical")]
    (OUT/"summary.json").write_text(json.dumps(dict(controlled=controls,equal_cost_layer=equal_layer,datasets=datasets),indent=2,allow_nan=False))
    figures(controls,datasets)
    for c in controls:
        print(json.dumps({k:v for k,v in c.items() if k!="trace"}))
    for r in datasets:
        print(json.dumps({k:v for k,v in r.items() if k!="trace"}))


if __name__=="__main__":
    main()
